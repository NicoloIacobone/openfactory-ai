#!/usr/bin/env python3
"""Spawn, remove and observe catalog objects in the running Gazebo world (harness tool).

Objects are created from the catalog (openfactory_description/config/objects.yaml) as SDF
generated by scene_objects, through the world's `create/blocking` and `remove/blocking`
services (they return once the entity exists or is gone; the plain ones only queue the request).

Ground truth: model poses are read straight from Gazebo (`/world/<world>/dynamic_pose/info`),
never republished on ROS, so no ROS node can consume them (rule 5); only the evaluation code of
the trial harness and this tool use them.

This is a harness tool: it changes the scene between trials, never during one, and it is not
part of perception or manipulation.

Run in the VM with the cell launched:
    python3 scripts/gz_scene.py spawn cube [--bin input] [--x 0 --y 0 --yaw 0] [--name cube]
    python3 scripts/gz_scene.py remove cube
    python3 scripts/gz_scene.py poses cube cylinder [--watch 5]
"""

import argparse
import sys
import threading
import time
from pathlib import Path

import yaml
from ament_index_python.packages import get_package_share_directory
from gz.msgs10.boolean_pb2 import Boolean
from gz.msgs10.entity_factory_pb2 import EntityFactory
from gz.msgs10.entity_pb2 import Entity
from gz.msgs10.pose_v_pb2 import Pose_V
from gz.transport13 import Node

import scene_objects as so

WORLD = 'cell'
TIMEOUT_MS = 5000


def load_config():
    share = Path(get_package_share_directory('openfactory_description')) / 'config'
    catalog = yaml.safe_load((share / 'objects.yaml').read_text())
    cell = yaml.safe_load((share / 'cell.yaml').read_text())
    return catalog, cell


class GzScene:

    def __init__(self, world=WORLD):
        self.world = world
        self.node = Node()

    def _call(self, service, request, request_type, timeout_ms=TIMEOUT_MS):
        ok, reply = self.node.request(
            f'/world/{self.world}/{service}', request, request_type, Boolean, timeout_ms)
        if not ok or not reply.data:
            raise RuntimeError(f'/world/{self.world}/{service} failed (is the cell launched?)')

    def spawn(self, name, sdf, xyz, rpy=(0.0, 0.0, 0.0), timeout_ms=TIMEOUT_MS):
        """`timeout_ms`: a model of many links in a slow world takes longer than the default."""
        request = EntityFactory(sdf=sdf, name=name, allow_renaming=False)
        request.pose.position.x, request.pose.position.y, request.pose.position.z = xyz
        q = so.quaternion_from_rpy(*rpy)
        o = request.pose.orientation
        o.x, o.y, o.z, o.w = q
        self._call('create/blocking', request, EntityFactory, timeout_ms)

    def remove(self, name):
        self._call('remove/blocking', Entity(name=name, type=Entity.MODEL), Entity)

    def model_poses(self, names, timeout_s=2.0):
        """Ground truth {name: (xyz, quaternion xyzw)} from one dynamic-pose message.

        Top-level models in that message are in the world frame. Names not in the message
        (removed, or static models such as the fixtures) are missing from the result.
        """
        received = threading.Event()
        result = {}

        def on_poses(msg):
            if received.is_set():
                return
            for pose in msg.pose:
                if pose.name in names:
                    p, q = pose.position, pose.orientation
                    result[pose.name] = ((p.x, p.y, p.z), (q.x, q.y, q.z, q.w))
            received.set()

        topic = f'/world/{self.world}/dynamic_pose/info'
        if not self.node.subscribe(Pose_V, topic, on_poses):
            raise RuntimeError(f'cannot subscribe to {topic}')
        try:
            if not received.wait(timeout_s):
                raise RuntimeError(f'no message on {topic} (is the cell launched?)')
        finally:
            self.node.unsubscribe(topic)
        return result


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest='command', required=True)
    spawn = sub.add_parser('spawn', help='spawn a catalog object resting in a bin')
    spawn.add_argument('object', help='catalog name (cube, cylinder, prism)')
    spawn.add_argument('--bin', default='input', choices=['input', 'output'])
    spawn.add_argument('--x', type=float, default=0.0, help='m, in the bin frame')
    spawn.add_argument('--y', type=float, default=0.0, help='m, in the bin frame')
    spawn.add_argument('--yaw', type=float, default=0.0, help='rad, about the bin z axis')
    spawn.add_argument('--roll', type=float, default=0.0, help='rad, debugging only')
    spawn.add_argument('--pitch', type=float, default=0.0, help='rad, debugging only')
    spawn.add_argument('--name', help='model name (default: the object name)')
    remove = sub.add_parser('remove', help='remove a model by name')
    remove.add_argument('name')
    poses = sub.add_parser('poses', help='print ground-truth model poses (world frame)')
    poses.add_argument('names', nargs='+')
    poses.add_argument('--watch', type=float, default=0.0,
                       help='s; read again after this time and report the drift')
    args = parser.parse_args()

    scene = GzScene()
    if args.command == 'poses':
        first = scene.model_poses(args.names)
        if args.watch:
            time.sleep(args.watch)
        last = scene.model_poses(args.names) if args.watch else first
        for name in args.names:
            if name not in last:
                print(f'{name}: not in the world')
                continue
            (xyz, quat), start = last[name], first.get(name, last[name])[0]
            drift = max(abs(a - b) for a, b in zip(xyz, start))
            print(f'{name}: xyz {[round(v, 4) for v in xyz]} quat {[round(v, 4) for v in quat]}'
                  + (f' drift {drift * 1000:.2f} mm in {args.watch:g} s' if args.watch else ''))
        return 0
    if args.command == 'remove':
        scene.remove(args.name)
        print(f'removed {args.name}')
        return 0

    catalog, cell = load_config()
    spec = catalog['objects'][args.object]
    name = args.name or args.object
    xyz, yaw = so.spawn_pose(cell, args.bin, spec, args.x, args.y, args.yaw)
    if args.roll or args.pitch:
        # tilted debug spawns: lift by the bounding-box diagonal so nothing starts in contact
        xyz[2] += max(so.bounding_box(spec))
    scene.spawn(name, so.model_sdf(name, spec, catalog['friction']), xyz,
                (args.roll, args.pitch, yaw))
    print(f'spawned {name} at {[round(v, 4) for v in xyz]} rpy {(args.roll, args.pitch, yaw)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
